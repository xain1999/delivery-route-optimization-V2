"""Chapter 1: what Lakeshore Larder's routes cost.

Uses the Chapter 2 plan (results/ch02/results.json, produced by
ch02_experiments.py) and the cost model in vrpbook/costs.py.

    python examples/ch01_costs.py --book ../book
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from vrpbook.costs import CostModel
from vrpbook import plotting

HERE = Path(__file__).resolve().parent.parent

# Sources for every input are given in Chapter 1, change them for your company.
MEDIAN_ANNUAL_WAGE = 44_860      # BLS, light truck drivers, May 2025
PAID_HOURS_PER_YEAR = 2_080      # 40 h x 52 weeks
WAGE_SHARE_OF_COMPENSATION = 0.70  # BLS ECEC, private industry, June 2026
VEHICLE_COST_PER_MILE = 0.76     # IRS business standard mileage rate from 1 July 2026
SERVICE_MIN_PER_STOP = 5.0       # assumption: unload totes, hand over
SPEED_MPH = 15.0                 # same as Chapter 2
WORKING_DAYS = 300               # six days a week, minus holidays
FLEET = 4


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--book", type=Path, default=None)
    args = ap.parse_args()

    R = json.loads((HERE / "results" / "ch02" / "results.json").read_text())
    wage = MEDIAN_ANNUAL_WAGE / PAID_HOURS_PER_YEAR
    loaded = wage / WAGE_SHARE_OF_COMPENSATION
    model = CostModel(driver_cost_per_hour=loaded,
                      vehicle_cost_per_mile=VEHICLE_COST_PER_MILE,
                      service_minutes_per_stop=SERVICE_MIN_PER_STOP,
                      average_speed_mph=SPEED_MPH)

    rows = []
    for k, p in enumerate((p for p in R["cvrp"]["per_route"] if p["stops"] > 0), 1):
        d, v = model.route_cost(p["mi"], p["stops"])
        rows.append({"van": k, "stops": p["stops"], "miles": p["mi"],
                     "hours": model.route_hours(p["mi"], p["stops"]),
                     "driver": d, "vehicle": v})
    tot = {key: sum(r[key] for r in rows) for key in ("stops", "miles", "hours", "driver", "vehicle")}
    total_cost = tot["driver"] + tot["vehicle"]
    per_mile = model.cost_per_mile_driven
    one_mile_year = FLEET * WORKING_DAYS * round(per_mile, 2)   # as printed in the text
    drive_hours = tot["miles"] / SPEED_MPH

    out = {
        "wage": wage, "loaded": loaded, "rows": rows, "total": tot,
        "total_cost": total_cost, "cost_per_stop": total_cost / tot["stops"],
        "driver_share": 100 * tot["driver"] / total_cost,
        "per_mile": per_mile, "per_mile_time": loaded / SPEED_MPH,
        "one_mile_year": one_mile_year,
        "drive_share_of_hours": 100 * drive_hours / tot["hours"],
        "annual_cost": total_cost * WORKING_DAYS,
        # what the Chapter 2 balance trade-off costs per year
        "balance_extra_mi": R["balance"][-1]["total_mi"] - R["balance"][0]["total_mi"],
    }
    out["balance_extra_year"] = out["balance_extra_mi"] * per_mile * WORKING_DAYS
    # stops per hour and miles per stop
    out["stops_per_hour"] = tot["stops"] / tot["hours"]
    out["miles_per_stop"] = tot["miles"] / tot["stops"]
    (HERE / "results" / "ch01").mkdir(parents=True, exist_ok=True)
    (HERE / "results" / "ch01" / "results.json").write_text(json.dumps(out, indent=1))
    print(json.dumps(out, indent=1))

    if args.book:
        write_book_assets(args.book, out)


def write_book_assets(book: Path, o: dict) -> None:
    def money(x, d=2):
        return f"\\${x:,.{d}f}"
    m = {
        "annual-wage": f"\\${MEDIAN_ANNUAL_WAGE:,}", "wage": money(o["wage"]),
        "loaded": money(o["loaded"]), "wage-share": f"{100 * WAGE_SHARE_OF_COMPENSATION:.0f}",
        "vehicle-per-mile": money(VEHICLE_COST_PER_MILE), "service-min": f"{SERVICE_MIN_PER_STOP:.0f}",
        "speed": f"{SPEED_MPH:.0f}", "working-days": str(WORKING_DAYS),
        "total-cost": money(o["total_cost"], 0), "cost-per-stop": money(o["cost_per_stop"]),
        "driver-share": f"{o['driver_share']:.0f}", "per-mile": money(o["per_mile"]),
        "per-mile-time": money(o["per_mile_time"]),
        "one-mile-year": money(o["one_mile_year"], 0), "annual-cost": money(o["annual_cost"], 0),
        "drive-share-hours": f"{o['drive_share_of_hours']:.0f}",
        "service-share-hours": f"{100 - o['drive_share_of_hours']:.0f}",
        "total-hours": f"{o['total']['hours']:.1f}", "total-miles": f"{o['total']['miles']:.1f}",
        "balance-extra-mi": f"{o['balance_extra_mi']:.1f}",
        "balance-extra-year": money(o["balance_extra_year"], 0),
        "stops-per-hour": f"{o['stops_per_hour']:.1f}", "miles-per-stop": f"{o['miles_per_stop']:.2f}",
    }
    gen = book / "generated"
    gen.mkdir(parents=True, exist_ok=True)
    lines = ["% Generated by code/examples/ch01_costs.py -- do not edit."]
    lines += [f"\\SetResult{{ch01/{k}}}{{{v}}}" for k, v in sorted(m.items())]
    plotting.write_tex(gen / "ch01-results.tex", "\n".join(lines) + "\n", encoding="utf-8")

    rows = []
    for r in o["rows"]:
        rows.append(f"Van {r['van']} & {r['stops']} & {r['miles']:.1f} & {r['hours']:.2f} & "
                    f"{r['driver']:.2f} & {r['vehicle']:.2f} & {r['driver'] + r['vehicle']:.2f} \\\\")
    t = o["total"]
    rows.append("\\midrule")
    rows.append(f"Total & {t['stops']} & {t['miles']:.1f} & {t['hours']:.2f} & {t['driver']:.2f} & "
                f"{t['vehicle']:.2f} & {o['total_cost']:.2f} \\\\")
    plotting.write_tex(gen / "ch01-cost-table.tex", "\n".join(rows) + "\n", encoding="utf-8")
    _plot_costs(o, book / "figures" / "ch01" / "route-costs.pdf")


def _plot_costs(o: dict, path: Path) -> None:
    import matplotlib.pyplot as plt
    path.parent.mkdir(parents=True, exist_ok=True)
    plotting.use_book_style()
    fig, ax = plt.subplots(figsize=(5.2, 1.9))
    labels = [f"Van {r['van']}" for r in o["rows"]][::-1]
    drv = [r["driver"] for r in o["rows"]][::-1]
    veh = [r["vehicle"] for r in o["rows"]][::-1]
    ax.barh(labels, drv, height=0.55, color=plotting.ROUTE_COLORS[0], label="Driver time",
            edgecolor="white", linewidth=1.5)
    ax.barh(labels, veh, left=drv, height=0.55, color=plotting.ROUTE_COLORS[1],
            label="Vehicle (per mile)", edgecolor="white", linewidth=1.5, hatch="////")
    for y, (d, v) in enumerate(zip(drv, veh)):
        ax.annotate(f"${d + v:,.0f}", (d + v, y), xytext=(4, 0), textcoords="offset points",
                    va="center", fontsize=8, color=plotting.INK)
    ax.set_xlabel("cost of the route (US dollars)")
    ax.set_xlim(0, max(d + v for d, v in zip(drv, veh)) * 1.15)
    ax.grid(True, axis="x", color=plotting.GRID, linewidth=0.5)
    ax.set_axisbelow(True)
    for side in ("top", "right", "left"):
        ax.spines[side].set_visible(False)
    ax.tick_params(axis="y", length=0)
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.42), ncol=2, frameon=False)
    plotting.save(fig, path)
    plt.close(fig)


if __name__ == "__main__":
    main()
