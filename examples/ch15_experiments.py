"""Chapter 15: the routing service, measured.

    python examples/ch15_experiments.py --book ../book      # about 1 minute

Calls the service in-process (FastAPI's test client), measures response
times against solve times, and writes the golden plan used by the
regression test (tests/golden/tuesday_service.json).
"""
from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

from vrpbook import plotting

from fastapi.testclient import TestClient

from routing_service.app import app
from routing_service.samples import tuesday_request

HERE = Path(__file__).resolve().parent.parent
OUT = HERE / "results" / "ch15"
GOLDEN = HERE / "tests" / "golden" / "tuesday_service.json"


def run() -> dict:
    c = TestClient(app)
    R = {"sync": []}
    for limit in (1, 5):
        t = time.perf_counter()
        r = c.post("/plans/solve", json=tuesday_request(limit))
        wall = time.perf_counter() - t
        p = r.json()
        R["sync"].append({"limit": limit, "wall": wall, "solve": p["solve_seconds"],
                          "cost": p["cost"], "miles": p["miles"], "vans": len(p["routes"]),
                          "unassigned": len(p["unassigned"])})
        print(R["sync"][-1], flush=True)
    t = time.perf_counter()
    job = c.post("/plans", json=tuesday_request(30)).json()
    accepted = time.perf_counter() - t
    while (j := c.get(f"/plans/{job['id']}").json())["status"] not in ("done", "failed"):
        time.sleep(0.5)
    p = j["result"]
    R["job"] = {"accepted_s": accepted, "cost": p["cost"], "miles": p["miles"],
                "vans": len(p["routes"]), "solve": p["solve_seconds"]}
    GOLDEN.parent.mkdir(parents=True, exist_ok=True)
    GOLDEN.write_text(json.dumps({"cost": p["cost"], "miles": p["miles"],
                                  "vans": len(p["routes"]), "time_limit_s": 30}, indent=1))
    R["metrics"] = c.get("/metrics").text
    R["request_bytes"] = len(json.dumps(tuesday_request(5)))
    R["response_bytes"] = len(json.dumps(p))
    print(R["job"], flush=True)
    return R


def write_book_assets(book: Path, R: dict) -> None:
    gen = book / "generated"
    gen.mkdir(parents=True, exist_ok=True)
    m = {}
    for s in R["sync"]:
        k = s["limit"]
        m[f"sync{k}-wall"] = f"{s['wall']:.2f}"
        m[f"sync{k}-overhead-ms"] = f"{1000 * (s['wall'] - s['solve']):.0f}"
        m[f"sync{k}-cost"] = f"\\${s['cost']:,.0f}"
        m[f"sync{k}-vans"] = s["vans"]
    J = R["job"]
    m["job-accept-ms"] = f"{1000 * J['accepted_s']:.0f}"
    m["golden-cost"] = f"\\${J['cost']:,.0f}"
    m["golden-vans"] = J["vans"]
    m["golden-miles"] = f"{J['miles']:.0f}"
    m["request-kb"] = f"{R['request_bytes'] / 1024:.0f}"
    m["response-kb"] = f"{R['response_bytes'] / 1024:.0f}"
    lines = ["% Generated by code/examples/ch15_experiments.py -- do not edit."]
    lines += [f"\\SetResult{{ch15/{k}}}{{{v}}}" for k, v in sorted(m.items())]
    plotting.write_tex(gen / "ch15-results.tex", "\n".join(lines) + "\n", encoding="utf-8")
    (gen / "ch15-metrics.txt").write_text(R["metrics"], encoding="utf-8")
    print("book assets written")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--book", type=Path, default=None)
    ap.add_argument("--from-json", action="store_true")
    args = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / "results.json"
    R = json.loads(path.read_text()) if args.from_json else run()
    if not args.from_json:
        path.write_text(json.dumps(R, indent=1))
    if args.book:
        write_book_assets(args.book, R)


if __name__ == "__main__":
    main()
